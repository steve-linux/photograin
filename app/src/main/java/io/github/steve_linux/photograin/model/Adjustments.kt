@Serializable
data class GradientMap(
    val amount: Float = 0f,
    val shadow: Int = 0xff101830.toInt(),
    val middle: Int = 0xffa06464.toInt(),
    val highlight: Int = 0xffffe4ae.toInt(),
    val midpoint: Float = 0.5f,
)

@Serializable
data class GradingTone(val hue: Float = 0f, val saturation: Float = 0f, val luminance: Float = 0f)

@Serializable
data class ColorGrading(
    val shadows: GradingTone = GradingTone(),
    val midtones: GradingTone = GradingTone(),
    val highlights: GradingTone = GradingTone(),
    val global: GradingTone = GradingTone(),
    val balance: Float = 0f,
    val blending: Float = 0.5f,
)
